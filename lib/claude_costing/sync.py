"""Build prices.json from LiteLLM's price file at a pinned commit:
python3 lib/claude_costing sync [--commit SHA] [--from FILE] [--check] [--table FILE]

The only module here that touches the network, and only when run by hand or
by .github/workflows/prices-sync.yml: __init__.py never imports it. The
fetched file is data, parsed as JSON and bounds-checked, never executed.

Rules are tried in order, first match wins: one per listed version, then a
bare family alias priced as its newest version, then a family catch-all priced
as its most expensive one. Rules marked "manual": true are hand-kept (models
the source no longer lists) and survive a sync.
"""
import argparse
import difflib
import json
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.realpath(__file__))
REPO = "BerriAI/litellm"
PATH = "model_prices_and_context_window.json"
RATES = ("input", "output", "cache_read", "cache_write_5m", "cache_write_1h")
SOURCE_KEYS = {"input": "input_cost_per_token", "output": "output_cost_per_token",
               "cache_read": "cache_read_input_token_cost",
               "cache_write_5m": "cache_creation_input_token_cost",
               "cache_write_1h": "cache_creation_input_token_cost_above_1hr"}
MODEL_ID = re.compile(r"^claude-([a-z]+)-([0-9]+)(?:-([0-9]{1,2}))?(?:-[0-9]{8})?$")
EXACT_RULE = re.compile(r"^\(?([a-z|]+)\)?-([0-9]+)(?:-([0-9]+))?\(\?!")
TIER_KEY = re.compile(r"_above_([0-9]+)k_tokens$")
MAX_BYTES = 64 << 20
ABOUT = ("List prices in USD per 1M tokens, generated by lib/claude_costing/sync.py from the file "
         "named in source; rules marked manual are hand-kept. Rules are tried in order and the "
         "first whose regex is found in the model name wins: listed versions, then a bare family "
         "alias at its newest version, then a family catch-all at its most expensive one. A model "
         "no rule names prices at the fallback, the most expensive tier, so a new model reads as "
         "expensive rather than free. A rule's above object prices a whole request whose prompt "
         "(input, cache reads and cache writes) is over prompt_tokens. Not modelled: fast mode, "
         "US-only inference (1.1x), web search fees, batch. An estimate for comparing work, not "
         "an invoice.")


class SyncError(Exception):
    pass


def fetch(url):
    # No auth and a generic agent: the request says nothing about who asks.
    req = urllib.request.Request(url, headers={"User-Agent": "prices-sync",
                                               "Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        body = r.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise SyncError(f"{url}: larger than {MAX_BYTES} bytes")
    return json.loads(body)


def newest_commit():
    got = fetch(f"https://api.github.com/repos/{REPO}/commits?path={PATH}&per_page=1")
    if not isinstance(got, list) or not got:
        raise SyncError(f"no commit touches {PATH} in {REPO}")
    return got[0]


def source_at(commit):
    """(LiteLLM's table, the source record) at a commit, the newest if none is named."""
    if commit is None:
        meta = newest_commit()
    else:
        if not re.fullmatch(r"[0-9a-f]{40}", commit):
            raise SyncError("--commit takes a full 40-hex SHA")
        meta = fetch(f"https://api.github.com/repos/{REPO}/commits/{commit}")
    sha = meta["sha"]
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise SyncError(f"unexpected commit id {sha!r}")
    date = str(meta["commit"]["committer"]["date"])[:10]
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", date):
        raise SyncError("unexpected commit date")
    data = fetch(f"https://raw.githubusercontent.com/{REPO}/{sha}/{PATH}")
    return data, {"repo": REPO, "path": PATH, "commit": sha, "date": date}


def per_million(row, key, model):
    v = row.get(key)
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise SyncError(f"{model}: {key} is missing or not a number")
    v = round(v * 1e6, 6)
    return int(v) if v == int(v) else v


def check_bounds(r, what):
    """The cheap things a wrong unit, a swapped column or a zeroed row breaks."""
    bad = []
    if not all(0.001 <= r[k] <= 1000 for k in RATES):
        bad.append("a rate outside 0.001..1000 USD per 1M tokens")
    if not r["output"] > r["input"]:
        bad.append("output is not above input")
    if not r["cache_read"] < r["input"]:
        bad.append("cache_read is not below input")
    if not r["input"] <= r["cache_write_5m"] <= r["cache_write_1h"]:
        bad.append("not input <= cache_write_5m <= cache_write_1h")
    if bad:
        raise SyncError(f"{what}: {'; '.join(bad)}: {json.dumps(r)}")


def model_rates(model, row):
    """One source row as a rule's rates, with its above tier if it has one."""
    r = {k: per_million(row, key, model) for k, key in SOURCE_KEYS.items()}
    check_bounds(r, model)
    tiers = {int(m[1]) for m in (TIER_KEY.search(k) for k in row) if m}
    if len(tiers) > 1:
        raise SyncError(f"{model}: more than one prompt-size tier ({sorted(tiers)}), which a rule cannot say")
    for k in tiers:
        above = {name: per_million(row, f"{key}_above_{k}k_tokens", model)
                 for name, key in SOURCE_KEYS.items()}
        check_bounds(above, f"{model} above {k}k")
        if any(above[name] < r[name] for name in RATES):
            raise SyncError(f"{model}: a rate above {k}k tokens is below its base rate")
        r["above"] = {"prompt_tokens": k * 1000, **above}
    return r


def source_versions(data):
    """{(family, (major, minor)): rates} for the source's Anthropic rows, and
    the ids whose shape names no version."""
    if not isinstance(data, dict):
        raise SyncError("the source is not a JSON object")
    versions, ids, skipped = {}, {}, []
    for model in sorted(data):
        row = data[model]
        if not isinstance(row, dict) or row.get("litellm_provider") != "anthropic":
            continue
        m = MODEL_ID.match(model)
        if not m:
            skipped.append(model)
            continue
        key = (m[1], (int(m[2]), int(m[3]) if m[3] else -1))
        r = model_rates(model, row)
        if key in versions and versions[key] != r:
            raise SyncError(f"{ids[key]} and {model} are one version at different prices")
        versions[key], ids[key] = r, model
    if not versions:
        raise SyncError("the source lists no Anthropic model with a version")
    return versions, skipped


def manual_versions(table):
    """The hand-kept rules of an existing table, keyed like source_versions."""
    out = {}
    for rule in (table or {}).get("rules", []):
        if not rule.get("manual"):
            continue
        m = EXACT_RULE.match(rule.get("match", ""))
        if not m or any(k not in rule for k in RATES):
            raise SyncError(f"manual rule is not a version rule with five rates: {json.dumps(rule)}")
        r = {k: v for k, v in rule.items() if k not in ("match", "manual")}
        check_bounds(r, f"manual rule {rule['match']}")
        for family in m[1].split("|"):
            out[(family, (int(m[2]), int(m[3]) if m[3] else -1))] = r
    return out


def families_re(families):
    return families[0] if len(families) == 1 else "(" + "|".join(families) + ")"


def exact_match(families, version):
    major, minor = version
    if minor < 0:
        # A date may follow a bare major (opus-4-20250514); a minor may not.
        return f"{families_re(families)}-{major}(?![0-9]|-[0-9]{{1,2}}(?![0-9]))"
    return f"{families_re(families)}-{major}-{minor}(?![0-9])"


def dearest(rates_list):
    return max(rates_list, key=lambda r: (r["output"], r["input"], r["cache_write_1h"],
                                          r["cache_write_5m"], r["cache_read"]))


def grouped(pairs):
    """[(families, value)] from (family, value) pairs: families that share a value share a rule."""
    groups = {}
    for family, value in sorted(pairs, key=lambda p: p[0]):
        groups.setdefault(json.dumps(value, sort_keys=True), ([], value))[0].append(family)
    return sorted(groups.values(), key=lambda g: g[0])


def build(data, old=None, source=None):
    """The table for a source file, keeping old's manual rules; (table, notes)."""
    versions, skipped = source_versions(data)
    # The ids are the source's text and the notes reach a pull request: echo only plain ones.
    plain = [m for m in skipped if re.fullmatch(r"[a-z0-9.-]{1,60}", m)]
    notes = [f"skipped {m}: no version in the id" for m in plain]
    if len(plain) < len(skipped):
        notes.append(f"skipped {len(skipped) - len(plain)} more ids of no known shape")
    manual = set()
    for key, r in manual_versions(old).items():
        if key not in versions:
            versions[key] = r
            manual.add(key)
        elif versions[key] != r:
            raise SyncError(f"manual rule for {key[0]} {key[1]} disagrees with the source; "
                            "remove it or correct it")
        else:
            notes.append(f"dropped the manual rule for {key[0]} {key[1]}: the source lists it now")
    families = sorted({f for f, _ in versions})
    rules = []
    for fams, (version, is_manual, r) in sorted(
            grouped((f, (v, (f, v) in manual, r)) for (f, v), r in versions.items()),
            key=lambda g: (g[0][0], [-n for n in g[1][0]])):
        rules.append({"match": exact_match(fams, tuple(version)), **r,
                      **({"manual": True} if is_manual else {})})
    newest = {f: max(v for g, v in versions if g == f) for f in families}
    for fams, r in grouped((f, versions[(f, newest[f])]) for f in families):
        rules.append({"match": f"^(claude-)?{families_re(fams)}($|\\[)", **r})
    for fams, r in grouped((f, dearest([r for (g, _), r in versions.items() if g == f]))
                           for f in families):
        rules.append({"match": "|".join(fams), **r})
    # The dearest model the source lists: a retired one does not price what is new.
    listed = [r for key, r in versions.items() if key not in manual]
    fallback = {k: v for k, v in dearest(listed).items() if k != "above"}
    table = {"about": ABOUT, "source": source or {"repo": REPO, "path": PATH, "commit": None, "date": None},
             "rules": rules, "fallback": fallback}
    return table, notes


def dumps(table):
    """One rule per line, so a price change is a one-line diff."""
    rules = table.get("rules", [])
    lines = ["{", f'  "about": {json.dumps(table.get("about"))},',
             f'  "source": {json.dumps(table.get("source"))},', '  "rules": [']
    lines += [f"    {json.dumps(r)}{',' if i < len(rules) - 1 else ''}" for i, r in enumerate(rules)]
    lines += ["  ],", f'  "fallback": {json.dumps(table.get("fallback"))}', "}"]
    return "\n".join(lines) + "\n"


def differences(old, new):
    """Unified diff lines between two tables, their source records left out."""
    def body(t):
        return dumps({**t, "source": None}).splitlines() if t else []
    return list(difflib.unified_diff(body(old), body(new), "committed", "generated", lineterm="", n=0))


def main(argv):
    ap = argparse.ArgumentParser(prog="claude_costing sync", description=__doc__.split("\n\n")[0])
    ap.add_argument("--commit", help="the source commit (40 hex); the newest that touches the file if omitted")
    ap.add_argument("--from", dest="file", help="read the source from a local file, no network")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 and print the differences")
    ap.add_argument("--table", default=os.path.join(HERE, "prices.json"), help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    try:
        old = None
        if os.path.exists(args.table):
            with open(args.table, encoding="utf-8") as f:
                old = json.load(f)
        if args.file:
            with open(args.file, encoding="utf-8") as f:
                data = json.load(f)
            source = {"repo": REPO, "path": PATH, "commit": args.commit, "date": None}
        else:
            data, source = source_at(args.commit)
        table, notes = build(data, old, source)
    except (SyncError, OSError, ValueError, KeyError, TypeError) as e:
        print(f"sync: {e}", file=sys.stderr)
        return 2
    for n in notes:
        print(f"sync: {n}", file=sys.stderr)
    diff = differences(old, table)
    if not diff:
        # The pin moves only with the prices, so a quiet week makes no diff.
        print(f"sync: {args.table} matches the source at {source['commit'] or args.file}")
        return 0
    print("\n".join(diff))
    if args.check:
        return 1
    with open(args.table, "w", encoding="utf-8") as f:
        f.write(dumps(table))
    print(f"sync: wrote {args.table} from {source['commit'] or args.file}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
